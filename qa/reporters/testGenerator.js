import fs from 'fs';
import path from 'path';

export class TestGenerator {
  constructor(outputDir = 'generated-tests') {
    this.outputDir = outputDir;
    fs.mkdirSync(this.outputDir, { recursive: true });
  }

  /**
   * Generates a clean, reproducible Playwright spec file from a tested workflow.
   * @param {string} testName - e.g. "auth_login_dashboard"
   * @param {Array<string>} steps - Step descriptions
   * @param {string} baseURL - target URL
   */
  generatePlaywrightTest(testName, steps = [], baseURL = 'http://localhost:5173') {
    const filename = `${testName.toLowerCase().replace(/[^a-z0-9_-]/g, '_')}.spec.js`;
    const targetPath = path.join(this.outputDir, filename);

    let code = `// Auto-generated by Autonomous QA (Open-QA & Playwright)\n`;
    code += `// Date: ${new Date().toISOString()}\n\n`;
    code += `import { test, expect } from '@playwright/test';\n\n`;
    code += `test.describe('Automated QA Workflow: ${testName}', () => {\n`;
    code += `  test('should execute reproducible flow', async ({ page }) => {\n`;
    code += `    // Step 1: Navigate to Base URL\n`;
    code += `    await page.goto('${baseURL}');\n\n`;

    steps.forEach((step, idx) => {
      code += `    // Step ${idx + 2}: ${step}\n`;
    });

    code += `    // Assertion: Page loaded and responsive\n`;
    code += `    await expect(page).toHaveURL(/.*(dashboard|login|leads|bookings).*/);\n`;
    code += `  });\n`;
    code += `});\n`;

    fs.writeFileSync(targetPath, code, 'utf-8');
    return targetPath;
  }
}
